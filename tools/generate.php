<?php

/*
 * Writes the binding from tools/api.json and tools/bindings.php:
 *
 *   stubs/<header>.stub.php   functions, struct classes and constants of each Raven header
 *   src/gen/<header>.c        one ZEND_FUNCTION per function, the struct constructors, the header's MINIT
 *   src/gen/structs.c/.h      field tables of the struct classes
 *   src/gen/callbacks.c/.h    one trampoline per callback typedef
 *   src/gen/minit.c           calls every header's MINIT
 *
 *   php84 tools/generate.php && php84 /opt/homebrew/opt/php@8.4/lib/php/build/gen_stub.php stubs
 *
 * Prints "bound N, manual M, not bound K, pending P". P must be 0.
 */

declare(strict_types=1);

$root = dirname(__DIR__);
$api = json_decode(file_get_contents("$root/tools/api.json"), true, 512, JSON_THROW_ON_ERROR);
$cfg = require "$root/tools/bindings.php";

$G = new Gen($api, $cfg);
$G->run($root);

final class Gen
{
    private array $enums = [];
    private array $structs;
    private array $callbacks;
    private array $pending = [];
    private array $usedTrampolines = [];
    private int $bound = 0;

    public function __construct(private array $api, private array $cfg)
    {
        foreach ($api['enums'] as $name => $_) {
            $this->enums[$name] = true;
        }
        $this->structs = $api['structs'];
        $this->callbacks = $api['callbacks'];
    }

    // ---------------------------------------------------------------- types

    private function norm(string $t): string
    {
        return trim(preg_replace('/\s+/', ' ', $t));
    }

    private function base(string $t): string
    {
        return trim(preg_replace('/^const /', '', $this->norm($t)));
    }

    private function scalar(string $t): ?string
    {
        $t = $this->base($t);

        return match (true) {
            in_array($t, ['Rid', 'Ruint', 'uint32_t'], true) => 'u32',
            $t === 'int' => 'int',
            isset($this->enums[$t]) => 'enum',
            $t === 'float' => 'float',
            $t === 'double' => 'double',
            $t === 'size_t' => 'size',
            $t === 'uint64_t' => 'u64',
            default => null,
        };
    }

    private function isStruct(string $t): bool
    {
        return isset($this->structs[$t]) && ! in_array($t, $this->cfg['manual_structs'], true);
    }

    // ---------------------------------------------------------------- run

    public function run(string $root): void
    {
        @mkdir("$root/src/gen", 0777, true);
        $byHeader = [];
        foreach ($this->api['headers'] as $h) {
            $byHeader[$h] = ['functions' => [], 'structs' => [], 'enums' => [], 'defines' => []];
        }
        foreach ($this->api['functions'] as $name => $fn) {
            $byHeader[$fn['header']]['functions'][$name] = $fn;
        }
        foreach ($this->structs as $name => $s) {
            if ($this->isStruct($name)) {
                $byHeader[$s['header']]['structs'][$name] = $s;
            }
        }
        foreach ($this->api['enums'] as $name => $e) {
            $byHeader[$e['header']]['enums'][$name] = $e;
        }
        foreach ($this->api['defines'] as $name => $d) {
            $byHeader[$d['header']]['defines'][$name] = $d;
        }

        $minits = [];
        foreach ($byHeader as $h => $parts) {
            $stem = basename($h, '.h');
            [$stub, $c] = $this->header($stem, $h, $parts);
            file_put_contents("$root/stubs/$stem.stub.php", $stub);
            file_put_contents("$root/src/gen/$stem.c", $c);
            $minits[] = $stem;
        }
        file_put_contents("$root/src/gen/structs.h", $this->structsH());
        file_put_contents("$root/src/gen/structs.c", $this->structsC());
        file_put_contents("$root/src/gen/callbacks.h", $this->callbacksH());
        file_put_contents("$root/src/gen/callbacks.c", $this->callbacksC());
        file_put_contents("$root/src/gen/minit.c", $this->minitC($minits));

        $manual = count($this->cfg['manual']);
        $nb = count($this->cfg['not_bound']);
        printf("bound %d, manual %d, not bound %d, pending %d\n", $this->bound, $manual, $nb, count($this->pending));
        foreach ($this->pending as $name => $why) {
            fwrite(STDERR, "pending: $name: $why\n");
        }
        exit($this->pending ? 1 : 0);
    }

    // ---------------------------------------------------------------- one header

    private function header(string $stem, string $h, array $parts): array
    {
        $stub = "<?php\n\n/** @generate-class-entries */\n\n/* Generated by tools/generate.php from lib/raven/include/raven/$h. Do not edit. */\n";
        $c = "/* Generated by tools/generate.php from lib/raven/include/raven/$h. Do not edit. */\n\n"
            . "#ifdef HAVE_CONFIG_H\n#include \"config.h\"\n#endif\n\n#include \"php.h\"\n#include \"zend_exceptions.h\"\n#include \"Raven.h\"\n"
            . "#include \"../runtime.h\"\n#include \"structs.h\"\n#include \"callbacks.h\"\n\n#include \"../../stubs/{$stem}_arginfo.h\"\n\n";

        foreach ($parts['enums'] as $ename => $e) {
            foreach ($e['constants'] as $k) {
                $stub .= "\n/**\n * @var int\n * @cvalue $k\n */\nconst $k = UNKNOWN;\n";
            }
        }
        foreach ($parts['defines'] as $dname => $d) {
            $type = str_starts_with($d['value'], '"') ? 'string' : 'int';
            $stub .= "\n/**\n * @var $type\n * @cvalue $dname\n */\nconst $dname = UNKNOWN;\n";
        }

        foreach ($parts['structs'] as $sname => $s) {
            [$cls, $ctor] = $this->structClass($sname, $s);
            $stub .= "\n$cls";
            $c .= $ctor;
        }

        foreach ($parts['functions'] as $name => $fn) {
            if (isset($this->cfg['not_bound'][$name]) || isset($this->cfg['manual'][$name])) {
                continue;
            }
            $r = $this->func($name, $fn);
            if ($r === null) {
                continue;
            }
            [$decl, $body] = $r;
            $stub .= "\n$decl\n";
            $c .= $body . "\n";
            $this->bound++;
        }

        $c .= "void raven_gen_{$stem}_minit(int module_number)\n{\n";
        if ($parts['enums'] || $parts['defines']) {
            $c .= "\tregister_{$stem}_symbols(module_number);\n";
        } else {
            $c .= "\t(void)module_number;\n";
        }
        $c .= "\tzend_register_functions(NULL, ext_functions, NULL, MODULE_PERSISTENT);\n";
        foreach ($parts['structs'] as $sname => $_) {
            $c .= "\traven_ce_$sname = register_class_$sname();\n";
        }
        $c .= "}\n";

        return [$stub, $c];
    }

    // ---------------------------------------------------------------- structs

    private function fieldKind(string $sname, array $f, array $fields): ?array
    {
        $t = $this->norm($f['type']);
        if (preg_match('/^(float|int) ?\[(\d+)\]$/', $t, $m)) {
            return [$m[1] === 'float' ? 'FLOATS' : 'INTS', (int) $m[2], null, 'array', '[' . implode(', ', array_fill(0, (int) $m[2], $m[1] === 'float' ? '0.0' : '0')) . ']'];
        }
        if (preg_match('/^char ?\[(\d+)\]$/', $t, $m)) {
            return ['CHARS', (int) $m[1], null, 'string', "''"];
        }
        if ($t === 'const char *') {
            return ['CSTR', 0, null, '?string', 'null'];
        }
        if (in_array($t, ['void *', 'uintptr_t', 'intptr_t'], true) || isset($this->callbacks[$t])) {
            return ['ADDR', 0, null, 'int', '0'];
        }
        if (preg_match('/^const (\w+) \*$/', $t, $m) || $t === 'const char *const *') {
            // An array whose count is the next int field.
            $idx = array_search($f, $fields, true);
            $countIdx = null;
            for ($i = $idx + 1; $i < count($fields); $i++) {
                if (in_array($this->norm($fields[$i]['type']), ['int', 'Ruint'], true) && str_contains($fields[$i]['name'], 'count')) {
                    $countIdx = $i;
                    break;
                }
            }
            if ($countIdx === null) {
                return null;
            }
            if ($t === 'const char *const *') {
                return ['STRS', $countIdx + 1, null, '?array', 'null'];
            }
            if ($this->isStruct($m[1])) {
                return ['STRUCTS', $countIdx + 1, $m[1], '?array', 'null'];
            }

            return null;
        }
        if ($this->isStruct($t)) {
            return ['STRUCT', 0, $t, $t, null];
        }

        return match ($this->scalar($t)) {
            'u32' => ['U32', 0, null, 'int', '0'],
            'int', 'enum' => ['INT', 0, null, 'int', '0'],
            'float' => ['FLOAT', 0, null, 'float', '0.0'],
            'double' => ['DOUBLE', 0, null, 'float', '0.0'],
            'size', 'u64' => ['U64', 0, null, 'int', '0'],
            default => null,
        };
    }

    private array $structTables = [];

    private function structClass(string $sname, array $s): array
    {
        $props = [];
        $params = [];
        $table = [];
        foreach ($s['fields'] as $f) {
            $k = $this->fieldKind($sname, $f, $s['fields']);
            if ($k === null) {
                $this->pending["struct $sname"] = "field {$f['name']}: {$f['type']}";

                return ['', ''];
            }
            [$kind, $count, $sub, $ptype, $default] = $k;
            if ($kind === 'STRUCT') {
                // Nested struct: a fresh object; PHP cannot default a property to one.
                $props[] = "    public $ptype \${$f['name']};";
                $params[] = "?$ptype \${$f['name']} = null";
            } else {
                // gen_stub cannot default a property to a non-empty array: the constructor fills it.
                $propDefault = in_array($kind, ['FLOATS', 'INTS'], true) ? '[]' : $default;
                $props[] = "    public $ptype \${$f['name']} = $propDefault;";
                $params[] = "$ptype \${$f['name']} = $default";
            }
            $subRef = $sub ? "&raven_struct_$sub" : 'NULL';
            $table[] = "\t{\"{$f['name']}\", offsetof($sname, {$f['name']}), RAVEN_F_$kind, $count, $subRef},";
        }
        $this->structTables[$sname] = $table;
        $cls = "final class $sname\n{\n" . implode("\n", $props) . "\n\n    public function __construct(" . implode(', ', $params) . ") {}\n}\n";
        $ctor = "ZEND_METHOD($sname, __construct)\n{\n\traven_struct_construct(&raven_struct_$sname, Z_OBJ_P(ZEND_THIS), execute_data);\n}\n\n";

        return [$cls, $ctor];
    }

    private function structsH(): string
    {
        $out = "/* Generated by tools/generate.php. Do not edit. */\n\n#ifndef RAVEN_GEN_STRUCTS_H\n#define RAVEN_GEN_STRUCTS_H\n\n#include \"../runtime.h\"\n\n";
        foreach ($this->structTables as $name => $_) {
            $out .= "extern zend_class_entry *raven_ce_$name;\nextern const raven_struct raven_struct_$name;\n";
        }

        return $out . "\n#endif\n";
    }

    private function structsC(): string
    {
        $out = "/* Generated by tools/generate.php. Do not edit. */\n\n#ifdef HAVE_CONFIG_H\n#include \"config.h\"\n#endif\n\n#include <stddef.h>\n#include \"php.h\"\n#include \"Raven.h\"\n#include \"structs.h\"\n\n";
        foreach ($this->structTables as $name => $_) {
            $out .= "zend_class_entry *raven_ce_$name;\n";
        }
        foreach ($this->structTables as $name => $rows) {
            $out .= "\nstatic const raven_field raven_fields_{$name}[] = {\n" . implode("\n", $rows) . "\n\t{NULL, 0, RAVEN_F_END, 0, NULL},\n};\n";
            $out .= "const raven_struct raven_struct_$name = {\"$name\", sizeof($name), &raven_ce_$name, raven_fields_$name};\n";
        }

        return $out;
    }

    // ---------------------------------------------------------------- functions

    /** @return array{0:string,1:string}|null */
    private function func(string $name, array $fn): ?array
    {
        $params = $fn['params'];
        $n = count($params);
        $byName = [];
        foreach ($params as $i => $p) {
            $byName[$p['name']] = $i;
        }

        $stubParams = [];
        $decls = [];
        $parse = [];
        $conv = [];     // scalar conversions, first
        $checks = [];   // buffer and array checks, after every scalar is known
        $args = [];
        $post = [];
        $cleanup = [];
        $arena = false;
        $slotInfo = null;
        $skip = [];     // C params consumed by another (user_data)
        $argNum = 0;
        $phpIndex = [];

        $uh = $this->cfg['user_handles'][$name] ?? null;
        $uhGetter = null;
        foreach ($this->cfg['user_handles'] as $setter => $u) {
            if ($u['get'] === $name) {
                $uhGetter = $u;
            }
        }

        foreach ($params as $i => $p) {
            if (isset($skip[$i])) {
                continue;
            }
            $argNum++;
            $phpIndex[$i] = $argNum;
            $pn = $p['name'];
            $t = $this->norm($p['type']);
            $v = "c_$pn";
            $sc = $this->scalar($t);

            if ($sc !== null && ! str_contains($t, '*')) {
                $decls[] = "\tzend_long $pn;";
                $parse[] = "\t\tZ_PARAM_LONG($pn)";
                $stubParams[] = "int \$$pn";
                switch ($sc) {
                    case 'u32':
                        $decls[] = "\tuint32_t $v;";
                        $conv[] = "\tif (!raven_arg_u32($pn, $argNum, &$v)) {\n\t\tRETURN_THROWS();\n\t}";
                        $args[$i] = $v;
                        break;
                    case 'int':
                    case 'enum':
                        $decls[] = "\tint $v;";
                        $conv[] = "\tif (!raven_arg_int($pn, $argNum, &$v)) {\n\t\tRETURN_THROWS();\n\t}";
                        $args[$i] = $sc === 'enum' ? "($t)$v" : $v;
                        break;
                    case 'size':
                        $decls[] = "\tsize_t $v;";
                        $conv[] = "\tif (!raven_arg_size($pn, $argNum, &$v)) {\n\t\tRETURN_THROWS();\n\t}";
                        $args[$i] = $v;
                        break;
                    case 'u64':
                        $decls[] = "\tuint64_t $v;";
                        $conv[] = "\tif (!raven_arg_u64($pn, $argNum, &$v)) {\n\t\tRETURN_THROWS();\n\t}";
                        $args[$i] = $v;
                        break;
                    case 'float':
                    case 'double':
                        array_pop($decls);
                        array_pop($parse);
                        array_pop($stubParams);
                        $decls[] = "\tdouble $pn;";
                        $parse[] = "\t\tZ_PARAM_DOUBLE($pn)";
                        $stubParams[] = "float \$$pn";
                        $args[$i] = $sc === 'float' ? "(float)$pn" : $pn;
                        break;
                }
                continue;
            }

            if ($t === 'const char *') {
                $decls[] = "\tzend_string *$pn = NULL;";
                $parse[] = "\t\tZ_PARAM_STR_OR_NULL($pn)";
                $stubParams[] = "?string \$$pn";
                $args[$i] = "$pn ? ZSTR_VAL($pn) : NULL";
                // Text sized by the next size_t: Raven reads that many bytes of it.
                if (isset($params[$i + 1]) && $this->norm($params[$i + 1]['type']) === 'size_t') {
                    $sizeName = $params[$i + 1]['name'];
                    $checks[] = "\tif ($pn && !raven_arg_length($pn, $argNum, c_$sizeName)) {\n\t\tRETURN_THROWS();\n\t}";
                }
                continue;
            }

            // Out-parameter: pointer to a scalar or enum.
            if (preg_match('/^(\w+) \*$/', $t, $m) && ($osc = $this->scalar($m[1])) !== null) {
                $decls[] = "\tzval *$pn;";
                $parse[] = "\t\tZ_PARAM_ZVAL($pn)";
                $stubParams[] = (in_array($osc, ['float', 'double'], true) ? '?float' : '?int') . " &\$$pn";
                $ctype = $m[1];
                $decls[] = "\t$ctype $v = 0;";
                $args[$i] = "&$v";
                $post[] = in_array($osc, ['float', 'double'], true)
                    ? "\tZEND_TRY_ASSIGN_REF_DOUBLE($pn, (double)$v);"
                    : "\tZEND_TRY_ASSIGN_REF_LONG($pn, (zend_long)$v);";
                continue;
            }

            if ($t === 'const char **') {
                $decls[] = "\tzval *$pn;";
                $parse[] = "\t\tZ_PARAM_ZVAL($pn)";
                $stubParams[] = "?string &\$$pn";
                $decls[] = "\tconst char *$v = NULL;";
                $args[$i] = "&$v";
                $post[] = "\tif ($v) {\n\t\tZEND_TRY_ASSIGN_REF_STRING($pn, $v);\n\t} else {\n\t\tZEND_TRY_ASSIGN_REF_NULL($pn);\n\t}";
                continue;
            }

            // Callback + its user data.
            if (isset($this->callbacks[$t])) {
                $cbs = [[$i, $t]];
                $udIndex = null;
                for ($j = $i + 1; $j < $n; $j++) {
                    $tj = $this->norm($params[$j]['type']);
                    if (isset($this->callbacks[$tj])) {
                        $cbs[] = [$j, $tj];
                        $skip[$j] = true;
                    } elseif ($tj === 'void *' && $params[$j]['name'] === 'user_data') {
                        $udIndex = $j;
                        $skip[$j] = true;
                        break;
                    }
                }
                if ($udIndex === null || count($cbs) > 2) {
                    $this->pending[$name] = 'callback without user_data';

                    return null;
                }
                foreach ($cbs as $w => [$ci, $ct]) {
                    $cn = $params[$ci]['name'];
                    $decls[] = "\tzend_fcall_info fci_$cn = empty_fcall_info;\n\tzend_fcall_info_cache fcc_$cn = empty_fcall_info_cache;";
                    $parse[] = "\t\tZ_PARAM_FUNC_OR_NULL(fci_$cn, fcc_$cn)";
                    $stubParams[] = "?callable \$$cn";
                    if ($w > 0) {
                        $argNum++;
                    }
                    $this->usedTrampolines[$ct][$w] = true;
                }
                $udName = $params[$udIndex]['name'];
                $decls[] = "\tzval *$udName;";
                $parse[] = "\t\tZ_PARAM_ZVAL($udName)";
                $stubParams[] = "mixed \$$udName";
                $argNum++;
                $slotInfo = ['cbs' => $cbs, 'ud' => $udName, 'udIndex' => $udIndex, 'at' => $i];
                foreach ($cbs as $w => [$ci, $ct]) {
                    $args[$ci] = "ZEND_FCI_INITIALIZED(fci_{$params[$ci]['name']}) ? raven_cb_{$ct}_$w : NULL";
                }
                $args[$udIndex] = 'slot';
                continue;
            }

            // User handle.
            if ($t === 'void *' && $uh !== null) {
                $decls[] = "\tzval *$pn;";
                $parse[] = "\t\tZ_PARAM_ZVAL($pn)";
                $stubParams[] = "mixed \$$pn";
                $args[$i] = "Z_TYPE_P($pn) == IS_NULL ? NULL : (void *)$pn";
                continue;
            }

            if ($t === 'RPainter *') {
                $decls[] = "\tzend_object *$pn;\n\tRPainter *$v;";
                $parse[] = "\t\tZ_PARAM_OBJ_OF_CLASS($pn, raven_ce_RPainter)";
                $stubParams[] = "RPainter \$$pn";
                $conv[] = "\t$v = raven_painter_get($pn, $argNum);\n\tif (!$v) {\n\t\tRETURN_THROWS();\n\t}";
                $args[$i] = $v;
                continue;
            }

            // const uint8_t* RGBA pixels sized by the next two int parameters
            // (width/height, or pixels_width/pixels_height when width/height are already the destination).
            if ($t === 'const uint8_t *' && isset($params[$i + 1], $params[$i + 2])
                && $this->norm($params[$i + 1]['type']) === 'int'
                && $this->norm($params[$i + 2]['type']) === 'int') {
                $wName = $params[$i + 1]['name'];
                $hName = $params[$i + 2]['name'];
                $decls[] = "\tzend_string *$pn;";
                $parse[] = "\t\tZ_PARAM_STR($pn)";
                $stubParams[] = "string \$$pn";
                $checks[] = "\tif (!raven_arg_bytes($pn, $argNum, c_$wName < 0 ? 0 : (uint64_t)c_$wName, c_$hName < 0 ? 0 : (uint64_t)c_$hName, 4, \"width x height RGBA pixels\")) {\n\t\tRETURN_THROWS();\n\t}";
                $args[$i] = "(const uint8_t *)ZSTR_VAL($pn)";
                continue;
            }

            // const void* followed by a size_t: bytes, the size as given and at most the string's length.
            if (in_array($t, ['const void *', 'const uint8_t *'], true) && isset($params[$i + 1]) && $this->norm($params[$i + 1]['type']) === 'size_t') {
                $sizeName = $params[$i + 1]['name'];
                $decls[] = "\tzend_string *$pn;";
                $parse[] = "\t\tZ_PARAM_STR($pn)";
                $stubParams[] = "string \$$pn";
                $checks[] = "\tif (!raven_arg_length($pn, $argNum, c_$sizeName)) {\n\t\tRETURN_THROWS();\n\t}";
                $args[$i] = "($t)ZSTR_VAL($pn)";
                continue;
            }

            // Arrays with a count parameter after them, or const float* sized by the two
            // preceding ints (Rchart_set_grid: rows, columns).
            if (in_array($t, ['const double *', 'const float *', 'const char *const *'], true) || (preg_match('/^const (\w+) \*$/', $t, $m) && $this->isStruct($m[1]) && $this->countParam($params, $i) !== null)) {
                $countName = $this->countParam($params, $i);
                $rowsName = null;
                $colsName = null;
                if ($countName === null && $t === 'const float *' && $i >= 2
                    && $this->norm($params[$i - 2]['type']) === 'int'
                    && $this->norm($params[$i - 1]['type']) === 'int') {
                    $rowsName = $params[$i - 2]['name'];
                    $colsName = $params[$i - 1]['name'];
                }
                if ($countName === null && $rowsName === null) {
                    $this->pending[$name] = "array $pn without a count";

                    return null;
                }
                $arena = true;
                $decls[] = "\tHashTable *$pn;";
                $parse[] = "\t\tZ_PARAM_ARRAY_HT($pn)";
                $stubParams[] = "array \$$pn";
                if ($t === 'const double *') {
                    $decls[] = "\tdouble *$v = NULL;";
                    $checks[] = "\tif (!raven_arg_doubles($pn, $argNum, c_$countName, &$v, &arena)) {\n\t\traven_arena_free(&arena);\n\t\tRETURN_THROWS();\n\t}";
                } elseif ($t === 'const float *') {
                    $decls[] = "\tfloat *$v = NULL;";
                    if ($rowsName !== null) {
                        $decls[] = "\tint {$v}_count = 0;";
                        $checks[] = "\tif (c_$rowsName > 0 && c_$colsName > 0 && __builtin_mul_overflow(c_$rowsName, c_$colsName, &{$v}_count)) {\n\t\tzend_argument_value_error($argNum, \"must hold $rowsName x $colsName values, whose size overflows\");\n\t\tRETURN_THROWS();\n\t}\n\tif (!raven_arg_floats($pn, $argNum, {$v}_count, &$v, &arena)) {\n\t\traven_arena_free(&arena);\n\t\tRETURN_THROWS();\n\t}";
                    } else {
                        $checks[] = "\tif (!raven_arg_floats($pn, $argNum, c_$countName, &$v, &arena)) {\n\t\traven_arena_free(&arena);\n\t\tRETURN_THROWS();\n\t}";
                    }
                } elseif ($t === 'const char *const *') {
                    $decls[] = "\tconst char **$v = NULL;";
                    $checks[] = "\tif (!raven_arg_strings($pn, $argNum, c_$countName, &$v, &arena)) {\n\t\traven_arena_free(&arena);\n\t\tRETURN_THROWS();\n\t}";
                } else {
                    $decls[] = "\t{$m[1]} *$v = NULL;";
                    $checks[] = "\tif (!raven_arg_structs($pn, $argNum, c_$countName, &raven_struct_{$m[1]}, (void **)&$v, &arena)) {\n\t\traven_arena_free(&arena);\n\t\tRETURN_THROWS();\n\t}";
                }
                $args[$i] = $v;
                continue;
            }

            // Single struct, in or in/out.
            if (preg_match('/^(const )?(\w+) \*$/', $t, $m) && $this->isStruct($m[2])) {
                $st = $m[2];
                $arena = true;
                $decls[] = "\tzend_object *$pn = NULL;\n\t$st $v;\n\t$st *p_$pn = NULL;";
                // Every Raven function taking a struct pointer accepts NULL (checked in its source).
                $parse[] = "\t\tZ_PARAM_OBJ_OF_CLASS_OR_NULL($pn, raven_ce_$st)";
                $stubParams[] = "?$st \$$pn";
                if ($m[1] === '') {
                    $post[] = "\tif (p_$pn) {\n\t\traven_struct_to_object(&raven_struct_$st, &$v, $pn);\n\t}";
                }
                $checks[] = "\tif ($pn) {\n\t\tif (!raven_struct_from_object(&raven_struct_$st, $pn, &$v, &arena, $argNum)) {\n\t\t\traven_arena_free(&arena);\n\t\t\tRETURN_THROWS();\n\t\t}\n\t\tp_$pn = &$v;\n\t}";
                $args[$i] = "p_$pn";
                continue;
            }

            // An address (Vulkan handles): int.
            if ($t === 'void *') {
                $decls[] = "\tzend_long $pn;";
                $parse[] = "\t\tZ_PARAM_LONG($pn)";
                $stubParams[] = "int \$$pn";
                $args[$i] = "(void *)(uintptr_t)$pn";
                continue;
            }

            $this->pending[$name] = "parameter $pn: $t";

            return null;
        }

        // ---- return
        $ret = $this->norm($fn['ret']);
        $retDecl = '';
        $retStmt = '';
        $retType = 'void';
        $rsc = $this->scalar($ret);
        if ($ret === 'void') {
            $retType = 'void';
        } elseif ($rsc !== null) {
            $ctype = $ret;
            $retDecl = "\t$ctype ret;";
            if (in_array($rsc, ['float', 'double'], true)) {
                $retType = 'float';
                $retStmt = "\tRETURN_DOUBLE((double)ret);";
            } else {
                $retType = 'int';
                $retStmt = "\tRETURN_LONG((zend_long)ret);";
            }
        } elseif ($ret === 'const char *') {
            $retType = '?string';
            $retDecl = "\tconst char *ret;";
            $retStmt = "\tif (!ret) {\n\t\tRETURN_NULL();\n\t}\n\tRETURN_STRING(ret);";
        } elseif ($ret === 'void *' && $uhGetter !== null) {
            $retType = 'mixed';
            $retDecl = "\tvoid *ret;";
            $retStmt = '__UH_GET__';
        } elseif ($ret === 'void *') {
            $retType = 'int';
            $retDecl = "\tvoid *ret;";
            $retStmt = "\tRETURN_LONG((zend_long)(uintptr_t)ret);";
        } elseif ($ret === 'const char *const *') {
            $countOut = null;
            foreach ($params as $p) {
                if (str_ends_with($this->norm($p['type']), '*') && $p['name'] === 'count') {
                    $countOut = $p['name'];
                }
            }
            if ($countOut === null) {
                $this->pending[$name] = "string list return without a count";

                return null;
            }
            $retType = 'array';
            $retDecl = "\tconst char *const *ret;";
            $retStmt = "\tarray_init(return_value);\n\tfor (uint32_t i = 0; ret && i < (uint32_t)c_$countOut; i++) {\n\t\tadd_next_index_string(return_value, ret[i]);\n\t}";
        } else {
            $this->pending[$name] = "return $ret";

            return null;
        }

        // ---- slot
        $slotPre = '';
        $slotPost = '';
        if ($slotInfo !== null) {
            $mode = $this->cfg['slots'][$name] ?? 'key';
            $cbNames = array_map(fn ($c) => $params[$c[0]]['name'], $slotInfo['cbs']);
            $fn0 = "ZEND_FCI_INITIALIZED(fci_{$cbNames[0]}) ? &fci_{$cbNames[0]}.function_name : NULL";
            $fn1 = isset($cbNames[1]) ? "ZEND_FCI_INITIALIZED(fci_{$cbNames[1]}) ? &fci_{$cbNames[1]}.function_name : NULL" : 'NULL';
            // Owner and key: the Rid and string parameters before the first callback.
            $ownerExpr = '0';
            $keyParts = [];
            $keyStr = null;
            if (is_array($mode)) {
                $ownerExpr = "c_{$mode['owner']}";
                $keyParts = array_map(fn ($k) => "(unsigned long)c_$k", $mode['key']);
            } else {
                for ($k = 0; $k < $slotInfo['at']; $k++) {
                    $pt = $this->norm($params[$k]['type']);
                    if ($pt === 'Rid') {
                        if ($ownerExpr === '0') {
                            $ownerExpr = "c_{$params[$k]['name']}";
                        }
                        $keyParts[] = "(unsigned long)c_{$params[$k]['name']}";
                    } elseif ($pt === 'const char *') {
                        $keyStr = $params[$k]['name'];
                    }
                }
            }
            $slotPre = "\tif (!raven_owner_check()) {\n\t\tRETURN_THROWS();\n\t}\n";
            $slotPre .= "\traven_slot *slot = raven_slot_new($fn0, $fn1, {$slotInfo['ud']}, $ownerExpr);\n";
            if ($mode === 'once') {
                $slotPre .= "\tif (slot) {\n\t\tslot->once = true;\n\t\tzend_string *key = raven_slot_key(\"$name\", 1, (unsigned long)++RAVEN_G(once_serial));\n\t\traven_slot_register(key, slot);\n\t\tzend_string_release(key);\n\t}\n";
            } elseif ($mode === 'return') {
                $slotPost = "\tif (slot) {\n\t\tif (ret != 0 && ret != R_INVALID_ID) {\n\t\t\tslot->owner = ret;\n\t\t\tzend_string *key = raven_slot_key(\"$name\", 1, (unsigned long)ret);\n\t\t\traven_slot_register(key, slot);\n\t\t\tzend_string_release(key);\n\t\t} else {\n\t\t\traven_slot_release(slot);\n\t\t}\n\t}\n";
            } else {
                $keyExpr = $keyStr !== null
                    ? "raven_slot_key_str(\"$name\", $keyStr ? ZSTR_VAL($keyStr) : NULL)"
                    : "raven_slot_key(\"$name\", " . count($keyParts) . ($keyParts ? ', ' . implode(', ', $keyParts) : '') . ')';
                // Registered before the call: Raven may call the new callback while it is being set.
                $slotPre .= "\tzend_string *key = $keyExpr;\n\traven_slot_register(key, slot);\n\tzend_string_release(key);\n";
            }
        }

        ksort($args);
        $call = "$name(" . implode(', ', array_values($args)) . ')';

        $body = "ZEND_FUNCTION($name)\n{\n";
        $body .= implode("\n", $decls) . ($decls ? "\n" : '');
        if ($arena) {
            $body .= "\traven_arena arena = {0};\n";
        }
        if ($retDecl !== '') {
            $body .= "$retDecl\n";
        }
        $total = count($parse);
        if ($total === 0) {
            $body .= "\n\tZEND_PARSE_PARAMETERS_NONE();\n";
        } else {
            $body .= "\n\tZEND_PARSE_PARAMETERS_START($total, $total)\n" . implode("\n", $parse) . "\n\tZEND_PARSE_PARAMETERS_END();\n";
        }
        if ($conv) {
            $body .= "\n" . implode("\n", $conv) . "\n";
        }
        if ($checks) {
            $body .= "\n" . implode("\n", $checks) . "\n";
        }
        $body .= "\n" . $slotPre;
        $body .= $arena ? "\tif (!raven_enter()) {\n\t\traven_arena_free(&arena);\n\t\tRETURN_THROWS();\n\t}\n" : "\tif (!raven_enter()) {\n\t\tRETURN_THROWS();\n\t}\n";
        $body .= $retDecl !== '' ? "\tret = $call;\n" : "\t$call;\n";
        $body .= "\traven_leave();\n";
        $body .= $slotPost;
        if ($uh !== null) {
            $first = $uh['key'][0];
            $parts = implode(', ', array_map(fn ($k) => "(unsigned long)c_$k", $uh['key']));
            $valName = null;
            foreach ($params as $p) {
                if ($this->norm($p['type']) === 'void *') {
                    $valName = $p['name'];
                }
            }
            $body .= "\tzend_string *key = raven_slot_key(\"$name\", " . count($uh['key']) . ", $parts);\n";
            $body .= "\traven_user_handle_set(key, c_$first, $valName);\n\tzend_string_release(key);\n";
        }
        if ($arena) {
            $body .= "\traven_arena_free(&arena);\n";
        }
        if ($post) {
            $body .= implode("\n", $post) . "\n";
        }
        if ($retStmt === '__UH_GET__') {
            $setter = array_search($uhGetter, $this->cfg['user_handles'], true);
            $parts = implode(', ', array_map(fn ($k) => "(unsigned long)c_$k", $uhGetter['key']));
            $retStmt = "\tif (!ret) {\n\t\tRETURN_NULL();\n\t}\n\tzend_string *key = raven_slot_key(\"$setter\", " . count($uhGetter['key']) . ", $parts);\n\traven_user_handle_get(key, return_value);\n\tzend_string_release(key);";
        }
        if ($retStmt !== '') {
            $body .= "$retStmt\n";
        }
        $body .= "}\n";

        $decl = "function $name(" . implode(', ', $stubParams) . "): $retType {}";

        return [$decl, $body];
    }

    private function countParam(array $params, int $i): ?string
    {
        for ($j = $i + 1; $j < count($params); $j++) {
            $pn = $params[$j]['name'];
            if (in_array($this->norm($params[$j]['type']), ['int', 'Ruint'], true) && ($pn === 'count' || str_ends_with($pn, '_count'))) {
                return $pn;
            }
        }

        return null;
    }

    // ---------------------------------------------------------------- callbacks

    private function callbacksH(): string
    {
        $out = "/* Generated by tools/generate.php. Do not edit. */\n\n#ifndef RAVEN_GEN_CALLBACKS_H\n#define RAVEN_GEN_CALLBACKS_H\n\n#include \"Raven.h\"\n\n";
        ksort($this->usedTrampolines);
        foreach ($this->usedTrampolines as $t => $which) {
            $cb = $this->callbacks[$t];
            foreach (array_keys($which) as $w) {
                $out .= $this->cbSignature($t, $cb, $w) . ";\n";
            }
        }

        return $out . "\n#endif\n";
    }

    private function cbSignature(string $t, array $cb, int $w): string
    {
        $ps = array_map(fn ($p) => $this->norm($p['type']) . ' ' . $p['name'], $cb['params']);

        return $this->norm($cb['ret']) . " raven_cb_{$t}_$w(" . ($ps ? implode(', ', $ps) : 'void') . ')';
    }

    private function callbacksC(): string
    {
        $out = "/* Generated by tools/generate.php. Do not edit. */\n\n#ifdef HAVE_CONFIG_H\n#include \"config.h\"\n#endif\n\n#include \"php.h\"\n#include \"zend_exceptions.h\"\n#include \"Raven.h\"\n#include \"../runtime.h\"\n#include \"structs.h\"\n#include \"callbacks.h\"\n";
        foreach ($this->usedTrampolines as $t => $which) {
            foreach (array_keys($which) as $w) {
                $out .= "\n" . $this->trampoline($t, $this->callbacks[$t], $w);
            }
        }

        return $out;
    }

    private function trampoline(string $t, array $cb, int $w): string
    {
        $ret = $this->norm($cb['ret']);
        $argc = count($cb['params']);
        $set = [];
        $after = [];
        $free = [];
        foreach ($cb['params'] as $k => $p) {
            $pt = $this->norm($p['type']);
            $pn = $p['name'];
            $sc = $this->scalar($pt);
            if ($pt === 'void *' && $pn === 'user_data') {
                $set[] = "\tZVAL_COPY(&args[$k], &slot->user_data);";
            } elseif ($sc !== null && ! str_contains($pt, '*')) {
                $set[] = in_array($sc, ['float', 'double'], true) ? "\tZVAL_DOUBLE(&args[$k], (double)$pn);" : "\tZVAL_LONG(&args[$k], (zend_long)$pn);";
            } elseif ($pt === 'const char *') {
                $set[] = "\tif ($pn) {\n\t\tZVAL_STRING(&args[$k], $pn);\n\t} else {\n\t\tZVAL_NULL(&args[$k]);\n\t}";
            } elseif ($pt === 'RPainter *') {
                $set[] = "\traven_painter_new($pn, &args[$k]);";
                $after[] = "\traven_painter_end(&args[$k]);";
            } elseif (preg_match('/^const (\w+) \*$/', $pt, $m) && $this->isStruct($m[1])) {
                $set[] = "\tif ($pn) {\n\t\traven_struct_new(&raven_struct_{$m[1]}, $pn, &args[$k]);\n\t} else {\n\t\tZVAL_NULL(&args[$k]);\n\t}";
            } elseif (preg_match('/^(\w+) \*$/', $pt, $m) && $this->isStruct($m[1])) {
                // Filled by the callable: its strings stay alive in the slot until the next call.
                $set[] = "\traven_struct_new(&raven_struct_{$m[1]}, $pn, &args[$k]);";
                $after[] = "\tif (invoked && $pn) {\n\t\traven_slot_keep(slot, &args[$k]);\n\t\tif (!raven_struct_from_object(&raven_struct_{$m[1]}, Z_OBJ(args[$k]), $pn, raven_slot_arena(slot), 1)) {\n\t\t\tmemset($pn, 0, sizeof(*$pn));\n\t\t}\n\t}";
            } elseif (preg_match('/^(float|int|double) \*$/', $pt, $m)) {
                $set[] = "\tZVAL_NEW_REF(&args[$k], &(zval){0});\n\t" . ($m[1] === 'int' ? "ZVAL_LONG(Z_REFVAL(args[$k]), $pn ? *$pn : 0);" : "ZVAL_DOUBLE(Z_REFVAL(args[$k]), $pn ? (double)*$pn : 0.0);");
                $after[] = "\tif (invoked && $pn) {\n\t\t*$pn = ({$m[1]})" . ($m[1] === 'int' ? "zval_get_long" : "zval_get_double") . "(Z_REFVAL(args[$k]));\n\t}";
            } else {
                $this->pending["callback $t"] = "parameter $pn: $pt";

                return '';
            }
            $free[] = "\tzval_ptr_dtor(&args[$k]);";
        }

        $hasUd = false;
        foreach ($cb['params'] as $p) {
            if ($p['name'] === 'user_data') {
                $hasUd = true;
            }
        }
        $sig = $this->cbSignature($t, $cb, $w);
        $out = "$sig\n{\n";
        $out .= $hasUd ? "\traven_slot *slot = user_data;\n" : "\traven_slot *slot = raven_slot_global(\"$t\");\n";
        $noop = match (true) {
            $ret === 'void' => 'return;',
            default => 'return 0;',
        };
        if ($ret === 'const char *') {
            $noop = 'return NULL;';
        }
        $out .= "\tif (!slot || !raven_on_owner_thread()) {\n\t\t$noop\n\t}\n";
        if ($ret !== 'void') {
            $out .= "\t$ret result = 0;\n";
        }
        $out .= "\tzval args[" . max(1, $argc) . "], rv;\n";
        $out .= implode("\n", $set) . "\n";
        $out .= "\tbool invoked = raven_invoke(slot, $w, &rv, $argc, args);\n";
        if ($ret !== 'void') {
            $out .= match ($ret) {
                'const char *' => "\tif (invoked) {\n\t\tresult = raven_slot_return_string(slot, &rv, \"$t\");\n\t}\n",
                default => "\tif (invoked) {\n\t\tresult = ($ret)raven_return_long(&rv, \"$t\");\n\t}\n",
            };
        }
        $out .= implode("\n", $after) . ($after ? "\n" : '');
        $out .= "\tif (invoked) {\n\t\tzval_ptr_dtor(&rv);\n\t}\n";
        $out .= implode("\n", $free) . "\n";
        if ($cb['ret'] !== 'void' && $this->norm($cb['ret']) !== 'void') {
            $out .= "\treturn result;\n";
        }
        $out .= "}\n";

        return $out;
    }

    // ---------------------------------------------------------------- minit

    private function minitC(array $stems): string
    {
        $out = "/* Generated by tools/generate.php. Do not edit. */\n\n#ifdef HAVE_CONFIG_H\n#include \"config.h\"\n#endif\n\n#include \"php.h\"\n\n";
        foreach ($stems as $s) {
            $out .= "void raven_gen_{$s}_minit(int module_number);\n";
        }
        $out .= "\nvoid raven_gen_minit(int module_number)\n{\n";
        foreach ($stems as $s) {
            $out .= "\traven_gen_{$s}_minit(module_number);\n";
        }

        return $out . "}\n";
    }
